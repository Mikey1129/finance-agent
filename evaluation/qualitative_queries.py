    """一个定性检索查询：问题 + 所属公司/期间 + 正确证据文本锚点。"""

    qid: str
    query: str
    company_name: str
    fiscal_year: int
    gold_phrases: list[str]  # 任一短语去空白后命中 chunk 文本即视为 gold 证据


